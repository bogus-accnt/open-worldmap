// Generates src/countries-db.js from tools/countries.csv (world-countries package).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseCSV } from "./csv.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

const rows = parseCSV(fs.readFileSync(path.join(here, "countries.csv"), "utf8"));

const entries = rows
  .filter((r) => r.cca2 && r.cca3 && r["name.common"])
  .map((r) => ({
    alpha2: r.cca2.toUpperCase(),
    alpha3: r.cca3.toUpperCase(),
    numeric: r.ccn3 ? r.ccn3.padStart(3, "0") : null,
    name: r["name.common"],
    region: r.region || null,
    subregion: r.subregion || null,
    independent: r.independent === "true",
  }))
  .sort((a, b) => a.alpha2.localeCompare(b.alpha2));

// Kosovo is not in ISO 3166-1 but is used as a top-level code (user-assigned XK).
if (!entries.some((e) => e.alpha2 === "XK")) {
  entries.push({
    alpha2: "XK",
    alpha3: "XKX",
    numeric: null,
    name: "Kosovo",
    region: "Europe",
    subregion: "Southeast Europe",
    independent: false,
  });
  entries.sort((a, b) => a.alpha2.localeCompare(b.alpha2));
}

const data = entries
  .map(
    (e) =>
      `  ${JSON.stringify(e.alpha2)}: { alpha2: ${JSON.stringify(e.alpha2)}, alpha3: ${JSON.stringify(e.alpha3)}, numeric: ${JSON.stringify(e.numeric)}, name: ${JSON.stringify(e.name)}, region: ${JSON.stringify(e.region)}, subregion: ${JSON.stringify(e.subregion)}, independent: ${e.independent} }`
  )
  .join(",\n");

const out = `// GENERATED by tools/generate-db.mjs — do not edit by hand.
// SPDX-License-Identifier: MIT
// ISO 3166-1 country metadata (from the "world-countries" dataset), plus Kosovo (XK).
export const COUNTRIES = {
${data}
};

const BY_ALPHA3 = Object.fromEntries(
  Object.values(COUNTRIES).map((c) => [c.alpha3, c.alpha2])
);

/** List of all region names, sorted. */
export const REGIONS = [...new Set(Object.values(COUNTRIES).map((c) => c.region).filter(Boolean))].sort();

/**
 * Normalize a country code to ISO 3166-1 alpha-2.
 * Accepts alpha-2 or alpha-3, any case, with surrounding whitespace.
 * Returns the alpha-2 code, or null if unknown.
 */
export function normalizeCode(code) {
  if (typeof code !== "string") return null;
  const c = code.trim().toUpperCase();
  if (c in COUNTRIES) return c;
  if (c in BY_ALPHA3) return BY_ALPHA3[c];
  return null;
}

/** True if the code is a known alpha-2 or alpha-3 country code. */
export function isValidCode(code) {
  return normalizeCode(code) !== null;
}

/** English common name for a code (or null). */
export function countryName(code) {
  const c = normalizeCode(code);
  return c ? COUNTRIES[c].name : null;
}

/** All countries, optionally filtered by { region } or { text } (name/code match). */
export function listCountries({ region, text } = {}) {
  let list = Object.values(COUNTRIES);
  if (region) list = list.filter((c) => c.region === region);
  if (text) {
    const q = String(text).trim().toLowerCase();
    if (q) {
      list = list.filter(
        (c) =>
          c.name.toLowerCase().includes(q) ||
          c.alpha2.toLowerCase().startsWith(q) ||
          c.alpha3.toLowerCase().startsWith(q)
      );
    }
  }
  return list;
}
`;

fs.writeFileSync(path.join(root, "src", "countries-db.js"), out, "utf8");
console.log(`Wrote src/countries-db.js with ${entries.length} countries.`);
